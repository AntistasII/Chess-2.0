package chess.game;

/**
 * Стратегия выбора действия: позволяет подключить ИИ, не связывая игровую сессию с его реализацией.
 */
@FunctionalInterface
public interface MoveSelector {
    /**
     * Возвращает идентификатор одного из допустимых действий переданной позиции. Сессия передаёт копию со скрытыми чужими картами.
     */
    String choose(Game game);
}
